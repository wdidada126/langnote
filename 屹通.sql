			*,
			CASE
				WHEN TT.ETP_STAT = '1' THEN '待激活用户'
				WHEN TT.ETP_STAT = '2' THEN '高价值客户'
				WHEN TT.ETP_STAT = '3' THEN '中价值客户'
				WHEN TT.ETP_STAT = '4' THEN '低价值客户'
				WHEN TT.ETP_STAT = '5' THEN '无价值客户'
