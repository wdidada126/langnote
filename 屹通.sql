					WHEN MADT.ETP_ID is null THEN '0'
					ELSE '1'
				END AS IS_SETTLE_ACCOUNTS,
				T1.EMP_NUMBER,
				T1.SMAR_EMP_NUMBER
			FROM
				(
				SELECT
					*
				FROM
					(
					SELECT
						MCIT.*,
						MOIT.SPEC_ID,
						MOIT.AMT,
