					WHEN (T1.FIRST_COMMISSION_DATE = ''
					or T1.FIRST_COMMISSION_DATE is NULL) THEN ''
					ELSE CONCAT(SUBSTR(T1.FIRST_COMMISSION_DATE, 1, 4), '年', SUBSTR(T1.FIRST_COMMISSION_DATE, 6, 2), '月', SUBSTR(T1.FIRST_COMMISSION_DATE, 9, 2), '日')
				END AS FIRST_COMMISSION_DATE,
