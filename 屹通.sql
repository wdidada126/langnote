				T1.STATUS,
				T1.CREATE_TIME,
				T1.UPDATE_TIME,
				T1.CREATE_MAN,
				T1.LAST_MODI_MAN,
				T1.SPEC_ID,
				T1.PAY_DATE,
				T1.BANK_NAME,
				T1.CUSTOMER_RELATION,
				T1.ORDER_TIME,
				T1.USER_ROLE,
				T4.NAME PROD_NAME,
				T3.NAME SPEC_NAME,
				T1.AMT,
				CASE
					WHEN T1.AMT IS NULL THEN '-'
					ELSE FORMAT(T1.AMT, 2)
				END AS AMT_TXT,
				T1.ORDER_STAT,
				PARAM1.NAME ORDER_STAT_TXT,
				IFNULL(T9.PROV_NAME, T5.NAME) PROV_NAME,
				T6.NAME TENA_NAME,
				LEFT(T1.ORDER_TIME,
				10) ORDER_DATE,
				T3.EFF_DURA,
				T3.EFF_DURA_UNIT,
				CASE
					WHEN T1.CUST_ID IS NULL THEN ''
					WHEN T1.ORDER_STAT != '1' THEN 0
					WHEN T3.EFF_DURA_UNIT = '1' THEN DATEDIFF(DATE_ADD(LEFT(T1.ORDER_TIME, 10), INTERVAL T3.EFF_DURA YEAR ), DATE_FORMAT(NOW(), '%Y-%m-%d'))
					WHEN T3.EFF_DURA_UNIT = '2' THEN DATEDIFF(DATE_ADD(LEFT(T1.ORDER_TIME, 10), INTERVAL T3.EFF_DURA MONTH ), DATE_FORMAT(NOW(), '%Y-%m-%d'))
					WHEN T3.EFF_DURA_UNIT = '3' THEN DATEDIFF( DATE_ADD(LEFT(T1.ORDER_TIME, 10), INTERVAL T3.EFF_DURA DAY ), DATE_FORMAT(NOW(), '%Y-%m-%d'))
					ELSE 0
				END AS LEFT_DAYS,
				CASE
					WHEN ( T1.LOGIN_DATE = ''
					AND T1.ORDER_TIME != '') THEN '1'
					WHEN ( T1.LOGIN_DATE >= DATE_FORMAT(DATE_ADD(now(), INTERVAL -1 MONTH) , "%Y-%m-%d")
					AND T1.COMMISSION_DATE >= DATE_FORMAT(DATE_ADD(now(), INTERVAL -1 MONTH) , "%Y-%m-%d")
					AND T1.ORDER_TIME != '') THEN '2'
					WHEN ( T1.LOGIN_DATE >= DATE_FORMAT(DATE_ADD(now(), INTERVAL -1 MONTH) , "%Y-%m-%d")
					AND T1.COMMISSION_DATE < DATE_FORMAT(DATE_ADD(now(), INTERVAL -1 MONTH) , "%Y-%m-%d")
					AND T1.COMMISSION_DATE != ''
					AND T1.ORDER_TIME != '') THEN '3'
					WHEN ( T1.LOGIN_DATE >= DATE_FORMAT(DATE_ADD(now(), INTERVAL -1 MONTH) , "%Y-%m-%d")
					AND T1.COMMISSION_DATE = ''
					AND T1.ORDER_TIME != '') THEN '4'
					WHEN ( T1.LOGIN_DATE < DATE_FORMAT(DATE_ADD(now(), INTERVAL -1 MONTH) , "%Y-%m-%d")
					AND T1.LOGIN = '0'
					AND T1.COMMISSION_DATE = ''
					AND T1.ORDER_TIME != '') THEN '5'
					WHEN ( T1.LOGIN_DATE < DATE_FORMAT(DATE_ADD(now(), INTERVAL -1 MONTH) , "%Y-%m-%d")
					AND T1.COMMISSION_DATE != ''
					AND T1.ORDER_TIME != '') THEN '6'
					WHEN ( T1.ORDER_TIME >= DATE_FORMAT(DATE_ADD(now(), INTERVAL -1 MONTH) , "%Y-%m-%d")) THEN '7'
					ELSE '0'
				END AS ETP_STAT,
