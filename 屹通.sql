				WHEN TT.USER_ROLE = '1' THEN '管理者'
				WHEN TT.USER_ROLE = '2' THEN '财务'
				WHEN TT.USER_ROLE = '3' THEN '人事'
				WHEN TT.USER_ROLE = '4' THEN '代发'
				ELSE ''
			END AS USER_ROLE_DESC
		FROM
			(
			SELECT
				T1.CUST_ID,
				T1.TENA_ID,
				T1.EMP_ID,
				T1.ETP_ID,
				T1.EMP_CUST_NO,
				CONCAT(T1.NAME, IF(T1.DISSOLVE = '1', '（解散）', '')) NAME,
				T1.BUYER_NAME,
				T1.BUYER_TEL,
				T1.LOGIN_IP,
				T1.LOGIN_TIME,
